const generateHistory = (baseRisk, days = 30) => {
  const history = [];
  const now = new Date();
  let current = baseRisk;
  for (let i = days; i >= 0; i--) {
    const date = new Date(now);
    date.setDate(date.getDate() - i);
    // Simulate realistic fluctuation
    const delta = (Math.random() - 0.48) * 8;
    current = Math.max(5, Math.min(98, current + delta));
    history.push({
      date: date.toISOString().split('T')[0],
      riskScore: Math.round(current),
      rainfall_mm: Math.round(Math.random() * 80 + 5),
      soilMoisture_pct: Math.round(40 + Math.random() * 50),
    });
  }
  return history;
};

